/**
 * @file
 * Числа, от которых зависит и раскладка панели, и её геометрия в скине.
 *
 * Всё, что уезжает в winset, считается в пикселях BYOND: это пиксели CSS,
 * умноженные на devicePixelRatio. Всё, что живёт внутри страницы, — в CSS.
 */

/** Сколько сообщений можно держать набранными одновременно. */
export const MAX_ROWS = 4;

/**
 * Предел роста поля ввода в строках. Дальше поле начинает прокручиваться:
 * панель не имеет права закрыть собой половину карты.
 */
export const MAX_INPUT_LINES = 8;

/**
 * Ширина панели в пикселях BYOND. На широких экранах панель во всю карту
 * читается плохо: строка уезжает от глаз к краям монитора.
 */
export const PANEL_MAX_WIDTH = 1100;
export const PANEL_MIN_WIDTH = 280;

/**
 * Высота статус-строки карты (interface/skin.dmf, mapwindow.status_bar).
 * Панель садится ровно над ней, чтобы не закрывать подсказки под курсором.
 */
export const STATUS_BAR_HEIGHT = 16;

/** Сколько пикселей карты панель обязана оставить видимыми сверху. */
export const PANEL_TOP_MARGIN = 48;

/**
 * Порог, за которым сообщение перестаёт помещаться в один запрос к клиенту и
 * начинает резаться на куски. У кириллицы это примерно каждый третий символ,
 * поэтому считаем в байтах, а не в символах.
 */
export const SLOW_TRANSPORT_BYTES = 1800;

/**
 * С какой длины показывать счётчик символов. Короткие реплики в счётчике не
 * нуждаются, а мигающая цифра у каждой строки только мешает.
 */
export const COUNTER_THRESHOLD = 120;
